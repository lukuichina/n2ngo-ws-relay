import WebSocket from 'ws';

const ws = new WebSocket('ws://100.101.102.101:8787/n2n?community=myc');

ws.on('open', () => {
  console.log('WebSocket connected');
  
  // Send a SNPublicSecret request (10-byte PemData)
  const request = new Uint8Array([
    0x29, 0x7f, 0x03, 0x01, 0x01, 0x0e, 0x53, 0x4e, 0x50, 0x75, 0x62, 0x6c, 0x69, 0x63, 0x53, 0x65,
    0x63, 0x72, 0x65, 0x74, 0x01, 0xff, 0x80, 0x00, 0x01, 0x01, 0x01, 0x09, 0x50, 0x75, 0x62, 0x6c,
    0x69, 0x63, 0x4b, 0x65, 0x79, 0x01, 0x0a, 0x00, 0x00, 0x00, 0x0f, 0xff, 0x80, 0x01, 0x0a, 0x01,
    0x02, 0x0a, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x00
  ]);
  
  console.log('Sending request, length:', request.length);
  ws.send(request);
});

ws.on('message', (data) => {
  console.log('Received message, length:', data.length);
  console.log('First 20 bytes:', Array.from(data.slice(0, 20)).map(b => b.toString(16).padStart(2, '0')).join(' '));
});

ws.on('error', (error) => {
  console.error('WebSocket error:', error.message);
});

ws.on('close', () => {
  console.log('WebSocket closed');
});

setTimeout(() => {
  console.log('Timeout, closing...');
  ws.close();
}, 10000);
